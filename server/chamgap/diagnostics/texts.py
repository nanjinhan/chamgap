def text_for(code: str, sensor: str, variant: str | None = None) -> Text:
    base = TEXTS.get(f"{code}:{variant}") if variant else None
    t = base or TEXTS[code]
    fmt = {"sensor": SENSOR_NAMES.get(sensor, sensor), "pin": SENSOR_PINS.get(sensor, "")}
    return Text(
        t.title.format(**fmt),
        tuple(c.format(**fmt) for c in t.causes),
        tuple(c.format(**fmt) for c in t.checks),
    )


def fmt_dur(seconds: float) -> str:
    """경과 시간 한국어: 45초, 3분, 1시간 20분"""
    s = max(0, int(seconds))
    if s < 60:
        return f"{s}초"
    m = s // 60
    if m < 60:
        return f"{m}분"
    h, m = divmod(m, 60)
    return f"{h}시간" + (f" {m}분" if m else "")
